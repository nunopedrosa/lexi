 var current='pt-PT';
 function supported(lang){return lang==='en'||lang==='pt-PT';}
 function normalise(lang){
  if(!lang)return null;
  var value=String(lang).toLowerCase();
  if(value==='pt'||value.indexOf('pt-')===0)return 'pt-PT';
  if(value.indexOf('en')===0)return 'en';
  return null;
 }
 function t(key,vars){
  var catalogue=catalogues[current]||catalogues['pt-PT'];
  var text=catalogue[key];
  if(text==null)text=catalogues.en[key];
  if(text==null)text=catalogues['pt-PT'][key];
  if(text==null)text=key;
  if(vars){
   for(var name in vars){
    if(Object.prototype.hasOwnProperty.call(vars,name)){
     text=text.split('{'+name+'}').join(String(vars[name]));
    }
   }
  }
  return text;
 }
 function setLanguage(lang){
  var next=normalise(lang);
  current=next&&supported(next)?next:'pt-PT';
  return current;
 }
